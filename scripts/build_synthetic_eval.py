"""Build explicitly synthetic annotations and question sets from the toy corpus."""
import json
import re
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.cli import import_corpus
from app.schemas import Chunk, Entity, Relation
from app.settings import ROOT
from evalsuite.metrics import entity_scores
from evalsuite.extraction import spans
from ingest.extract import RuleExtractor
from retrieve.graph import EvidenceGraph


def read(path, model):
    return [model.model_validate_json(line) for line in path.read_text(encoding='utf-8').splitlines() if line]


def main():
    fixtures = ROOT / 'evalsuite/fixtures/corpus'
    records = ROOT / 'data/private/corpus'
    import_corpus(fixtures, records)
    chunks = read(records / 'chunks.jsonl', Chunk)
    entities = read(records / 'entities.jsonl', Entity)
    relations = read(records / 'relations.jsonl', Relation)
    # Gold annotations are generated by a separate, explicit fixture annotation pass.
    gold_rows = []
    geo = json.loads((ROOT / 'data/private/schools/schools.geojson').read_text(encoding='utf-8'))
    school_names = sorted({f['properties']['name'] for f in geo['features'] if f['properties'].get('name')}, key=len, reverse=True)
    school = re.compile(r'(?<!\w)(?:' + '|'.join(re.escape(n) for n in school_names) + r')(?!\w)', re.I)
    patterns = {'Board': r'\b(?:CBSE|ICSE|WBBSE)\b', 'Circular': r'\b(?:Circular|CIRCULAR)\s+[A-Z0-9/-]+', 'Rule': r'\bRule\s+\d+', 'Date': r'\b\d{4}-\d{2}-\d{2}\b', 'Quantity': r'\b\d+\s+(?:seats|years)\b|\b\d+%' }
    for chunk in chunks:
        found = []
        for kind, regex in [('School', school.pattern), *patterns.items()]:
            for m in re.finditer(regex, chunk.text, re.I):
                found.append({'type': kind, 'name': m.group(), 'start': m.start(), 'end': m.end()})
        gold_rows.append({'doc_id': chunk.document_id, 'chunk_id': chunk.id, 'text': chunk.text,
                          'entities': sorted(found, key=lambda x: (x['start'], x['end'], x['type'])), 'synthetic': True})
    # Exactly ten distinct annotated source documents as requested.
    docs = list(dict.fromkeys(row['doc_id'] for row in gold_rows))[:10]
    (ROOT / 'evalsuite/gold_entities.jsonl').write_text(''.join(json.dumps(r, ensure_ascii=False) + '\n' for r in gold_rows if r['doc_id'] in docs), encoding='utf-8')
    chunks_by_id = {c.id: c for c in chunks}
    gold_spans = [{'type': e['type'], 'document_id': c.document_id, 'page': c.page, 'start': e['start'], 'end': e['end']}
                  for row in gold_rows if row['doc_id'] in docs for c in [chunks_by_id[row['chunk_id']]] for e in row['entities']]
    school_entities = []
    entity_file = ROOT / 'data/private/schools/entities.jsonl'
    if entity_file.exists():
        school_entities = [Entity.model_validate_json(line) for line in entity_file.read_text(encoding='utf-8').splitlines() if line]
    extractor = RuleExtractor(school_entities)
    predicted = spans([e for c in chunks if c.document_id in docs for e in extractor.extract(c)], chunks_by_id)
    (ROOT / 'evidence/synthetic_assessment').mkdir(parents=True, exist_ok=True)
    (ROOT / 'evidence/synthetic_assessment/entity_metrics.json').write_text(json.dumps({
        'synthetic': True, 'gold_generated_by_independent_pattern_annotation': True,
        'rule_exact': entity_scores(predicted, gold_spans), 'rule_relaxed': entity_scores(predicted, gold_spans, True),
        'llm': 'not evaluated: smoke extractor failed strict validation'}, indent=2), encoding='utf-8')
    judgments = []
    for i in range(30):
        chunk = chunks[i % len(chunks)]
        split = 'tune' if i < 20 else 'holdout'
        qtype = ['exact_identifier', 'paraphrase', 'multi_hop', 'list', 'table'][i % 5]
        text = chunk.text
        if 'admission' in text.lower(): query = 'Summarize the school admission details in this synthetic circular.'
        elif 'seats' in text.lower(): query = 'How many Class 11 seats are offered and what is the age rule?'
        else: query = 'Which board and circular mention the named school?'
        judgments.append({'id': f'syn_q_{i+1:02d}', 'query': query, 'split': split, 'category': qtype,
                          'judgments': {chunk.id: 2, chunks[(i+1) % len(chunks)].id: 1}, 'synthetic': True})
    (ROOT / 'evalsuite/retrieval_judgments.jsonl').write_text(''.join(json.dumps(r) + '\n' for r in judgments), encoding='utf-8')
    calibrations = []
    for i in range(40):
        chunk = chunks[(i * 3) % len(chunks)]
        calibrations.append({'id': f'syn_cal_{i+1:02d}', 'query': 'What does this fictional admission circular say about seats and eligibility?',
                             'split': 'fit' if i < 25 else 'test', 'judgments': {chunk.id: 2, chunks[(i+1) % len(chunks)].id: 0}, 'synthetic': True})
    (ROOT / 'evalsuite/calibration_questions.jsonl').write_text(''.join(json.dumps(r) + '\n' for r in calibrations), encoding='utf-8')
    pairs=[]; seen_names=set()
    for feature in geo['features']:
        name=feature['properties'].get('name')
        if name and name.casefold() not in seen_names:
            seen_names.add(name.casefold());pairs.append((name,str(feature['properties']['osm_id'])))
        if len(pairs)>=10:break
    dev=[]
    for i,(name,osm) in enumerate(pairs,1):
        month=(i%12)+1; board=['CBSE','ICSE','WBBSE'][((i-1)%3)]; seats=60+10*i; cutoff=70+i; circ=f'CIRC-2026-{i:02d}'
        query=[f'How many seats does the fictional notice give {name}?',f'Which board is named for {name}?',
               f'When is the fictional application deadline for {name}?',f'What minimum age does the notice state for {name}?',
               f'What invented cutoff is listed for {name}?',f'Which circular mentions {name}?',
               f'Which rule is listed for {name}?',f'Which fictional locality is given for {name}?',
               f'Which earlier circular is superseded in the notice for {name}?',f'What OSM ID identifies {name} in the supplied map?'][i-1]
        required=[f'{name} hypothetically offers {seats} seats',f'{name} is affiliated with {board}',
                  f'Applications hypothetically close on 2026-{month:02d}-30', 'at least 14 years',
                  f'invented academic cut-off is {cutoff}% marks',circ,f'Rule {i}',f'Sector {i}',
                  f'Circular 2025-{i:02d}',osm][i-1]
        dev.append({'id':f'syn_dev_{i:02d}','query':query,'required_facts':[required],'synthetic':True})
    (ROOT / 'evalsuite/dev_questions.jsonl').write_text(''.join(json.dumps(r) + '\n' for r in dev), encoding='utf-8')
    graph = EvidenceGraph(entities, relations)
    counts = {'gold_docs': len(docs), 'gold_records': len([r for r in gold_rows if r['doc_id'] in docs]),
              'retrieval_tune': sum(x['split'] == 'tune' for x in judgments), 'retrieval_holdout': sum(x['split'] == 'holdout' for x in judgments),
              'calibration_fit': sum(x['split'] == 'fit' for x in calibrations), 'calibration_test': sum(x['split'] == 'test' for x in calibrations),
              'dev_questions': len(dev), 'synthetic': True, 'graph_stats': graph.statistics()}
    (ROOT / 'evidence/synthetic_assessment/dataset_manifest.json').write_text(json.dumps(counts, indent=2), encoding='utf-8')
    print(json.dumps(counts, indent=2))


if __name__ == '__main__':
    main()
